"""Compile the manuscript and the Supplementary Information with tectonic, report layout problems, render page previews.

Usage:  python build.py [manuscript|supplementary|all]
Prints every Overfull/Underfull box and undefined reference from the LaTeX log, then writes PNG previews of every
page to png/pages_<name>/ (for checking by eye; not part of the submission).
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import fitz  # PyMuPDF

HERE = Path(__file__).resolve().parent
TECTONIC = Path(r"C:\Users\USER\anaconda3\Library\bin\tectonic.exe")
PROBLEM = re.compile(r"(Overfull|Underfull|undefined|Undefined|multiply defined)")


def build(name: str) -> int:
    tex = HERE / f"{name}.tex"
    run = subprocess.run([str(TECTONIC), "--keep-logs", "--keep-intermediates", tex.name], cwd=HERE, capture_output=True, text=True)
    if run.returncode != 0:
        print(run.stdout[-3000:], run.stderr[-3000:])
        raise SystemExit(f"{name}: tectonic failed")
    problems = [line.strip() for line in (HERE / f"{name}.log").read_text(encoding="utf-8", errors="replace").splitlines() if PROBLEM.search(line)]
    pdf = fitz.open(HERE / f"{name}.pdf")
    out = HERE / "png" / f"pages_{name}"
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.png"):
        old.unlink()
    for i, page in enumerate(pdf):
        page.get_pixmap(dpi=80).save(out / f"p{i + 1:02d}.png")
    print(f"{name}: {pdf.page_count} pages, {len(problems)} layout warnings")
    for line in problems:
        print("   ", line)
    return len(problems)


CLEAN_OPTIONS = r"\documentclass[pdflatex,sn-nature]{sn-jnl}"
REVIEW_OPTIONS = r"\documentclass[referee,lineno,pdflatex,sn-nature]{sn-jnl}"


def build_review_copy() -> None:
    """Peer-review copy (double-spaced, line numbers) written from manuscript.tex; the source file is not changed."""
    text = (HERE / "manuscript.tex").read_text(encoding="utf-8")
    if CLEAN_OPTIONS not in text:
        raise SystemExit("manuscript.tex: class line not found; cannot make the review copy")
    (HERE / "manuscript_review.tex").write_text(
        "%% GENERATED by build.py from manuscript.tex -- do not edit; edit manuscript.tex instead.\n" + text.replace(CLEAN_OPTIONS, REVIEW_OPTIONS),
        encoding="utf-8")
    build("manuscript_review")


def main() -> None:
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    names = ["manuscript", "supplementary"] if which == "all" else [which]
    for name in names:
        if name == "review":
            build_review_copy()
        elif (HERE / f"{name}.tex").exists():
            build(name)
    if which == "all":
        build_review_copy()


if __name__ == "__main__":
    main()
